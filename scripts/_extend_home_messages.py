def atomic_write(target: str, content: str) -> str:
    target_dir = os.path.dirname(target) or "."
    fd, tmp = tempfile.mkstemp(prefix=".atomic_", dir=target_dir)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, target)
    except Exception:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise
    size = os.path.getsize(target)
    with open(target, "rb") as f:
        data = f.read()
    has_null = b"\x00" in data
    return "size=" + str(size) + " nulls=" + str(has_null)


def merge_home(path: str, new_home: dict) -> str:
    with open(path, "r", encoding="utf-8") as f:
        msgs = json.load(f)
    # Remplace intégralement le namespace Home par le nouveau
    msgs["Home"] = new_home
    content = json.dumps(msgs, ensure_ascii=False, indent=2) + "\n"
    return content


